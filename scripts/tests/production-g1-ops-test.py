class RuntimeAcceptanceTest(unittest.TestCase):
    """GO-5 acceptance checker against a synthetic /proc and systemd."""

    @classmethod
    def setUpClass(cls):
        cls.mod = load(OPS / "go5-runtime-acceptance.py", "go5_runtime_acceptance")

    def tree(self, *, production_label="wpcaregrid-mysql-production (enforce)", extra_listeners=(), x_port=False):
        root = Path(tempfile.mkdtemp(prefix="g1-go5-"))
        self.addCleanup(shutil.rmtree, root, True)
        procs = {"100": ("mysqld", "legacy", None), "200": ("mysqld", "wpcaregrid-production", production_label),
                 "300": ("mysqld", "wpcaregrid-production-restore", "wpcaregrid-mysql-production-restore (enforce)")}
        for pid, (comm, name, label) in procs.items():
            d = root / "proc" / pid
            (d / "attr").mkdir(parents=True)
            (d / "comm").write_text(comm + "\n")
            (d / "attr" / "current").write_text((label or "unconfined") + "\n")
            (d / "cmdline").write_bytes(f"/usr/sbin/mysqld\0--defaults-group-suffix=@{name}\0".encode())
        rows = ["  sl  local_address rem_address   st"]
        ports = [("0100007F", 3306), ("0100007F", 3308), ("0100007F", 3309), *extra_listeners]
        if x_port:
            ports.append(("0100007F", 33060))
        rows += [f"   0: {a}:{p:04X} 00000000:0000 0A 00000000" for a, p in ports]
        (root / "proc" / "net").mkdir(parents=True)
        (root / "proc" / "net" / "tcp").write_text("\n".join(rows) + "\n")
        return root

    def check(self, root, *, mysql_pid=100, active=True):
        pids = {"mysql.service": "100", "mysql@wpcaregrid-production.service": "200",
                "mysql@wpcaregrid-production-restore.service": "300"}

        def run(args):
            if args[1] == "is-active":
                return (0, "active\n") if active else (3, "inactive\n")
            return 0, pids[args[2]] + "\n"
        import contextlib
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            code = self.mod.main(mysql_pid, root=str(root), run=run)
        return code, buffer.getvalue().strip().splitlines()[-1]

    def test_pass(self):
        self.assertEqual(self.check(self.tree()), (0, "G1_GO5_RUNTIME_ACCEPTANCE=PASS"))

    def test_stops(self):
        cases = {
            "apparmor_label_not_enforced": self.tree(production_label="unconfined"),
            "instance_port_listening_beyond_loopback": self.tree(extra_listeners=[("00000000", 3308)]),
            "x_protocol_port_listening": self.tree(x_port=True),
        }
        for code, root in cases.items():
            with self.subTest(code=code):
                self.assertEqual(self.check(root), (3, f"G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE={code}"))
        self.assertEqual(self.check(self.tree(), mysql_pid=999),
                         (3, "G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE=mysql_service_main_pid_changed"))
        self.assertEqual(self.check(self.tree(), active=False),
                         (3, "G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE=unit_not_active"))


def docker_ready() -> bool:
    if shutil.which("docker") is None:
        return False
    build = subprocess.run(
        ["docker", "build", "-q", "-t", TEST_IMAGE, "-"],
        input=f"FROM {IMAGE}\nRUN microdnf install -y python3 tar && microdnf clean all\n".encode(),
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False, timeout=900)
    return build.returncode == 0


_READY = None


def ready() -> bool:
    global _READY
    if _READY is None:
        _READY = docker_ready()
    return _READY


def tar_of(files, execs=()):
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w") as archive:
        for path, content in sorted(files.items()):
            info = tarfile.TarInfo(path.lstrip("/"))
            info.size, info.mode, info.uid, info.gid = len(content), 0o644, 0, 0
            archive.addfile(info, io.BytesIO(content))
    return buffer.getvalue()



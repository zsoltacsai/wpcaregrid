def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


CONTRACT = load(SCRIPTS / "production_g1_mysql_contract.py", "production_g1_mysql_contract")
ENGINE = load(OPS / "g1-state-check.py", "g1_state_check")
sha = lambda data: hashlib.sha256(data).hexdigest()  # noqa: E731


class ToolkitStaticTest(unittest.TestCase):
    def test_toolkit_sha256sums_is_exact_and_complete(self):
        listed = {}
        raw = (OPS / "SHA256SUMS").read_bytes()
        self.assertTrue(raw.endswith(b"\n"))
        for line in raw.decode("ascii").splitlines():
            digest, name = line.split("  ", 1)
            listed[name] = digest
        actual = {p.name: sha(p.read_bytes()) for p in OPS.iterdir() if p.name != "SHA256SUMS"}
        self.assertEqual(listed, actual)

    def test_all_toolkit_sources_compile_and_are_lf_only(self):
        for path in OPS.iterdir():
            if path.name == "SHA256SUMS":
                continue
            self.assertNotIn(b"\r", path.read_bytes(), path.name)
            if path.suffix == ".py":
                compile(path.read_text(encoding="utf-8"), str(path), "exec")
            elif path.suffix == ".sh" and shutil.which("bash"):
                subprocess.run(["bash", "-n"], input=path.read_bytes(), check=True)

    def test_engine_expectations_equal_the_328_package_and_generated_artifacts(self):
        generated = {p: sha(b) for p, b in CONTRACT.artifact_files().items()}
        script = (SCRIPTS / "production-g1-mysql.py").read_bytes()
        contract = (SCRIPTS / "production_g1_mysql_contract.py").read_bytes()
        manifest_raw = (SCRIPTS / "production-g1-mysql-manifest.json").read_bytes()
        expected = {
            **generated,
            "/usr/local/libexec/wpcaregrid-g1-mysql.py": sha(script),
            "/usr/local/libexec/production_g1_mysql_contract.py": sha(contract),
            "/usr/local/libexec/production_g1_mysql_manifest.json": sha(manifest_raw),
        }
        self.assertEqual(ENGINE.EXPECTED["328"], expected)
        self.assertEqual(json.loads(manifest_raw)["installed_artifacts"],
                         {k: v for k, v in expected.items() if not k.endswith("manifest.json")})
        for path in ENGINE.CNF_ZZ:
            self.assertIn(path, generated)
        for path in ENGINE.CNF_90:
            self.assertNotIn(path, generated)

    def test_manifest_check_and_dryrun_and_diagnostic_pin_the_current_package(self):
        contract_sha = sha((SCRIPTS / "production_g1_mysql_contract.py").read_bytes())
        for name in ("go3-effective-config-dryrun.py", "g1-effective-config-check.py"):
            text = (OPS / name).read_text(encoding="utf-8")
            self.assertEqual(re.findall(r'CONTRACT_SHA256 = "([0-9a-f]{64})"', text), [contract_sha], name)
        manifest_check = (OPS / "go3-manifest-check.py").read_text(encoding="utf-8")
        for path, digest in CONTRACT.artifact_files().items():
            self.assertIn(f'"{path}": "{sha(digest)}"', manifest_check)
        self.assertNotIn("mysql.conf.d/90-", manifest_check)

    def test_fetch_script_pins_the_current_package_hashes(self):
        text = (OPS / "go3-fetch-package.sh").read_text(encoding="utf-8")
        for name in ("production-g1-mysql.py", "production_g1_mysql_contract.py", "production-g1-mysql-manifest.json"):
            self.assertIn(f"{sha((SCRIPTS / name).read_bytes())} {name}", text)
        self.assertIn(sha((SCRIPTS / "SHA256SUMS").read_bytes()) + " SHA256SUMS", text)
        self.assertRegex(text, r"\nM=[0-9a-f]{40}\n")
        self.assertIn("--proto '=https'", text)

    def test_rollback_script_targets_exactly_the_nine_325_files(self):
        text = (OPS / "go2-rollback.sh").read_text(encoding="utf-8")
        targets = re.findall(r'^"(/[^|"]+)\|([0-9a-f]{64})\|(\d+)"$', text, flags=re.M)
        self.assertEqual({p: h for p, h, _ in targets}, ENGINE.EXPECTED["325"])
        self.assertEqual(len(targets), 9)
        self.assertTrue(all("zz-" not in p for p, _, _ in targets))


class RuntimeAcceptanceTest(unittest.TestCase):
    """GO-5 acceptance checker against a synthetic /proc and systemd."""

    @classmethod
    def setUpClass(cls):
        cls.mod = load(OPS / "go5-runtime-acceptance.py", "go5_runtime_acceptance")

    def tree(self, *, production_label="wpcaregrid-mysql-production (enforce)", extra_listeners=(), x_port=False):
        root = Path(tempfile.mkdtemp(prefix="g1-go5-"))
        self.addCleanup(shutil.rmtree, root, True)
        procs = {"100": ("mysqld", "legacy", None), "200": ("mysqld", "wpcaregrid-production", production_label),
                 "300": ("mysqld", "wpcaregrid-production-restore", "wpcaregrid-mysql-production-restore (enforce)")}
        for pid, (comm, name, label) in procs.items():
            d = root / "proc" / pid
            (d / "attr").mkdir(parents=True)
            (d / "comm").write_text(comm + "\n")
            (d / "attr" / "current").write_text((label or "unconfined") + "\n")
            (d / "cmdline").write_bytes(f"/usr/sbin/mysqld\0--defaults-group-suffix=@{name}\0".encode())
        rows = ["  sl  local_address rem_address   st"]
        ports = [("0100007F", 3306), ("0100007F", 3308), ("0100007F", 3309), *extra_listeners]
        if x_port:
            ports.append(("0100007F", 33060))
        rows += [f"   0: {a}:{p:04X} 00000000:0000 0A 00000000" for a, p in ports]
        (root / "proc" / "net").mkdir(parents=True)
        (root / "proc" / "net" / "tcp").write_text("\n".join(rows) + "\n")
        return root

    def check(self, root, *, mysql_pid=100, active=True):
        pids = {"mysql.service": "100", "mysql@wpcaregrid-production.service": "200",
                "mysql@wpcaregrid-production-restore.service": "300"}

        def run(args):
            if args[1] == "is-active":
                return (0, "active\n") if active else (3, "inactive\n")
            return 0, pids[args[2]] + "\n"
        import contextlib
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            code = self.mod.main(mysql_pid, root=str(root), run=run)
        return code, buffer.getvalue().strip().splitlines()[-1]

    def test_pass(self):
        self.assertEqual(self.check(self.tree()), (0, "G1_GO5_RUNTIME_ACCEPTANCE=PASS"))

    def test_stops(self):
        cases = {
            "apparmor_label_not_enforced": self.tree(production_label="unconfined"),
            "instance_port_listening_beyond_loopback": self.tree(extra_listeners=[("00000000", 3308)]),
            "x_protocol_port_listening": self.tree(x_port=True),
        }
        for code, root in cases.items():
            with self.subTest(code=code):
                self.assertEqual(self.check(root), (3, f"G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE={code}"))
        self.assertEqual(self.check(self.tree(), mysql_pid=999),
                         (3, "G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE=mysql_service_main_pid_changed"))
        self.assertEqual(self.check(self.tree(), active=False),
                         (3, "G1_GO5_RUNTIME_ACCEPTANCE=STOP;CODE=unit_not_active"))


def docker_ready() -> bool:
    if shutil.which("docker") is None:
        return False
    build = subprocess.run(
        ["docker", "build", "-q", "-t", TEST_IMAGE, "-"],
        input=f"FROM {IMAGE}\nRUN microdnf install -y python3 tar && microdnf clean all\n".encode(),
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False, timeout=900)
    return build.returncode == 0


_READY = None


def ready() -> bool:
    global _READY
    if _READY is None:
        _READY = docker_ready()
    return _READY


def tar_of(files, execs=()):
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w") as archive:
        for path, content in sorted(files.items()):
            info = tarfile.TarInfo(path.lstrip("/"))
            info.size, info.mode, info.uid, info.gid = len(content), 0o644, 0, 0
            archive.addfile(info, io.BytesIO(content))
    return buffer.getvalue()


@unittest.skipUnless(ready() or REQUIRE, "Docker / MySQL image unavailable")
class DryRunAgainstRealMysqlTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not ready():
            raise AssertionError("G1_REQUIRE_REAL_MYSQL=1 but Docker or the MySQL image is unavailable")

    def run_dryrun(self, shared, *, package=None, extra_script=""):
        files = {
            "/etc/mysql/my.cnf": b"!includedir /etc/mysql/conf.d/\n!includedir /etc/mysql/mysql.conf.d/\n",
            "/pkg/production_g1_mysql_contract.py": package if package is not None else
                (SCRIPTS / "production_g1_mysql_contract.py").read_bytes(),
            "/ops/go3-effective-config-dryrun.py": (OPS / "go3-effective-config-dryrun.py").read_bytes(),
        }
        files.update({f"/etc/mysql/mysql.conf.d/{name}": body.encode() for name, body in shared.items()})
        script = ("tar -x -C / && chmod -R go-w /etc/mysql && chown -R root:root /pkg /etc/mysql /ops && "
                  + extra_script + "python3 -I -B /ops/go3-effective-config-dryrun.py /pkg; echo \"rc=$?\"; "
                  "ls -d /tmp/g1-dryrun-* 2>/dev/null | wc -l; ls /etc/mysql/mysql.conf.d")
        done = subprocess.run(["docker", "run", "--rm", "-i", "--entrypoint", "bash", TEST_IMAGE, "-c", script],
                              input=tar_of(files), stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False, timeout=300)
        return done.stdout.decode()

    UBUNTU = "[mysqld]\nuser=mysql\npid-file=/var/run/mysqld/mysqld.pid\nsocket=/var/run/mysqld/mysqld.sock\n" \
             "datadir=/var/lib/mysql\nlog-error=/var/log/mysql/error.log\nbind-address=127.0.0.1\nmysqlx-bind-address=127.0.0.1\n"

    def legacy_files(self):
        return {name.replace("zz-", "90-"): body.decode() for path, body in CONTRACT.artifact_files().items()
                if path.endswith(".cnf") for name in [path.rsplit("/", 1)[1]]}

    def test_vps_like_host_passes_and_leaves_no_trace(self):
        out = self.run_dryrun({"mysqld.cnf": self.UBUNTU, "99-wpcaregrid.cnf": "[mysqld]\nmax_connections=100\n",
                               **self.legacy_files()})
        self.assertIn("G1_GO3_DRYRUN=PASS", out)
        self.assertIn("rc=0", out)
        self.assertRegex(out, r"\n0\n")                      # no temp directory left behind
        self.assertIn("90-wpcaregrid-production.cnf", out)   # the host tree itself was not modified
        self.assertNotIn("zz-wpcaregrid", out)

    def test_a_later_shared_file_that_overrides_an_option_is_a_mismatch(self):
        out = self.run_dryrun({"mysqld.cnf": self.UBUNTU, "zzz-late.cnf": "[mysqld]\ndatadir=/var/lib/mysql\n"})
        self.assertIn("G1_GO3_DRYRUN=MISMATCH;INSTANCE=wpcaregrid-production;OPTION=datadir", out)
        self.assertIn("rc=3", out)

    def test_existing_zz_g1_file_and_tampered_contract_stop(self):
        out = self.run_dryrun({"mysqld.cnf": self.UBUNTU, "zz-wpcaregrid-production.cnf": "x"})
        self.assertIn("G1_GO3_DRYRUN=STOP;CODE=g1_option_file_already_present", out)
        out = self.run_dryrun({"mysqld.cnf": self.UBUNTU},
                              package=(SCRIPTS / "production_g1_mysql_contract.py").read_bytes() + b"#")
        self.assertIn("G1_GO3_DRYRUN=STOP;CODE=contract_file_hash_mismatch", out)



#!/usr/bin/env python3
"""GO-5.2c hotfix: replace exactly the installed G1 contract, manifest and the two AppArmor profiles.

Why: the confined `my_print_defaults` / mysqld of both instances is denied reading `/etc/mysql/mysql.cnf`
(`/etc/mysql/my.cnf` is an Ubuntu alternatives symlink whose AppArmor-mediated target is that file). The hotfix
contract generates both profiles with exactly one additional rule, `/etc/mysql/mysql.cnf r,`. The installer is
no-overwrite by design, so this tool is the only place that replaces installed bytes. It replaces only:
  /usr/local/libexec/production_g1_mysql_contract.py   /usr/local/libexec/production_g1_mysql_manifest.json
  /etc/apparmor.d/wpcaregrid-mysql-production          /etc/apparmor.d/wpcaregrid-mysql-production-restore
and reloads exactly those two named profiles (`apparmor_parser -r`). The helper (hash-pinned, unchanged), the option
files and the systemd drop-ins are not touched, nothing is initialized or started, `mysql.service`,
`/etc/mysql/my.cnf` and `/etc/apparmor.d/usr.sbin.mysqld` are not touched.

Usage (root):  python3 -I -B go5p-upgrade-apparmor.py <hotfix-package-dir>

Checks before any write: the package directory (root-owned, no symlinks) holds the contract and manifest with the
pinned hashes; the profiles generated by exactly those contract bytes have the pinned hashes and compile
(`apparmor_parser -Q -T`, no kernel load); the helper is the pinned one; contract, manifest and both profiles are
either all the pinned OLD or all the pinned NEW files; both G1 units are inactive; both profiles are loaded in
enforce mode; no leftover temporary file. Each replacement is a same-directory temporary file + fsync + atomic
rename (profile temporaries use the `.dpkg-new` suffix, which AppArmor's loader ignores). After the reload the
helper's static verification (`verify_static_install`, `check_base_config`) must pass and both profiles must be in
enforce mode; otherwise the old bytes are restored and the old profiles reloaded. Prints one tag line:
  G1_GO52C_PROFILE_UPGRADE=PASS[;NOTE=already_upgraded]                     exit 0
  G1_GO52C_PROFILE_UPGRADE=STOP;CODE=<cause>[;ROLLED_BACK=yes|NO]            exit 3
"""
import hashlib
import os
import re
import stat
import subprocess
import sys
import types

LIBEXEC = "/usr/local/libexec"
APPARMOR_DIR = "/etc/apparmor.d"
HELPER = LIBEXEC + "/wpcaregrid-g1-mysql.py"
CONTRACT = LIBEXEC + "/production_g1_mysql_contract.py"
MANIFEST = LIBEXEC + "/production_g1_mysql_manifest.json"
PROFILE_P = APPARMOR_DIR + "/wpcaregrid-mysql-production"
PROFILE_R = APPARMOR_DIR + "/wpcaregrid-mysql-production-restore"
PARSER = "/usr/sbin/apparmor_parser"
LOADED_PROFILES = "/sys/kernel/security/apparmor/profiles"
HELPER_SHA = "32da9353289e97f1c9974d544185f51b2fea45e0c926efaaf523753bfbfb528e"   # installed, unchanged
OLD = {  # installed after GO-5.2 hotfix
    CONTRACT: "45a9cab39c1276b7c9585c63b4204867ea8696b392589f750ba36cac972397a3",
    MANIFEST: "c2b693195f542ab88d261bd65dc586c56880526a65707c135cee2d29a61dea73",
    PROFILE_P: "5ad9b53b5a0001d32bffbd3e56d15d92158b026e9cf645411dda95d73f6478cd",
    PROFILE_R: "8210c0193f6487cf3f90d969560020b4e611d6e986341d28397510839872a72e",
}
NEW = {  # this hotfix package
    CONTRACT: "270a7f2ddc93a38bbabc94197e11fa078602004b39c18a2c86a34bf4c6f05f8f",
    MANIFEST: "70490acf887f3222ffaa0087c215826dc70a8b8cda7016d0f8807b7099cab6cb",
    PROFILE_P: "9a40053158880f0e6baf0db06431587651701487910634015e712e878dcfe13d",
    PROFILE_R: "ce56847e98f23b45590aaf55ad069df89f97dc12b672c2a289bb0fa7fb923b3e",
}
SOURCE_NAMES = {CONTRACT: "production_g1_mysql_contract.py", MANIFEST: "production-g1-mysql-manifest.json"}
PROFILE_NAMES = {PROFILE_P: "wpcaregrid-mysql-production", PROFILE_R: "wpcaregrid-mysql-production-restore"}
ORDER = (CONTRACT, MANIFEST, PROFILE_P, PROFILE_R)
MODES = {HELPER: 0o755, CONTRACT: 0o644, MANIFEST: 0o644, PROFILE_P: 0o644, PROFILE_R: 0o644}
UNITS = ("mysql@wpcaregrid-production.service", "mysql@wpcaregrid-production-restore.service")
STATIC_VERIFY_SNIPPET = (
    "import importlib.util, sys\n"
    "sys.dont_write_bytecode = True\n"
    "spec = importlib.util.spec_from_file_location('g1_helper_static_verify', " + repr(HELPER) + ")\n"
    "module = importlib.util.module_from_spec(spec)\n"
    "sys.modules[spec.name] = module\n"
    "spec.loader.exec_module(module)\n"
    "try:\n"
    "    module.verify_static_install()\n"
    "    module.check_base_config()\n"
    "    print('BASE_CONFIG_CHECK=PASS')\n"
    "except module.Refused as exc:\n"
    "    print('G1_MYSQL=STOP;CODE=%s' % exc)\n"
    "    raise SystemExit(3)\n"
)
ENV = {"PATH": "/usr/sbin:/usr/bin:/sbin:/bin", "HOME": "/nonexistent", "LANG": "C", "LC_ALL": "C"}


class Stop(Exception):
    def __init__(self, code, rolled_back=None):
        super().__init__(code)
        self.code, self.rolled_back = code, rolled_back


def temp_name(path):
    return path + (".dpkg-new" if path.startswith(APPARMOR_DIR + "/") else ".g1-upgrade-tmp")


def read_regular(path, mode):
    """Bytes of a root-owned regular file with exactly `mode` (None: any), never through a symlink."""
    st = os.lstat(path)
    if not stat.S_ISREG(st.st_mode):
        raise Stop("not_a_regular_file:" + os.path.basename(path))
    if st.st_uid != 0 or st.st_gid != 0:
        raise Stop("owner_invalid:" + os.path.basename(path))
    if mode is not None and stat.S_IMODE(st.st_mode) != mode:
        raise Stop("mode_invalid:" + os.path.basename(path))
    with open(path, "rb") as stream:
        return stream.read()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def default_run(args, data=None):
    return subprocess.run(args, input=data, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=120,
                          check=False, close_fds=True,
                          stdin=subprocess.DEVNULL if data is None else None, env=ENV)


def replace_atomic(path, content, mode):
    temp = temp_name(path)
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chown(temp, 0, 0)
        os.chmod(temp, mode)
        os.rename(temp, path)
    except BaseException:
        if os.path.lexists(temp):
            os.unlink(temp)
        raise
    directory = os.open(os.path.dirname(path), os.O_RDONLY)
    try:
        os.fsync(directory)
    finally:
        os.close(directory)


def generated_profiles(contract_bytes):
    """Profiles generated by exactly the (already hash-verified) contract bytes."""
    module = types.ModuleType("g1_hotfix_contract")
    module.__file__ = "<g1_hotfix_contract>"
    sys.modules[module.__name__] = module
    exec(compile(contract_bytes, "<g1_hotfix_contract>", "exec"), module.__dict__)
    files = module.artifact_files()
    return {path: files[path] for path in (PROFILE_P, PROFILE_R)}


def loaded_enforce(path=LOADED_PROFILES):
    with open(path, encoding="utf-8") as stream:
        lines = stream.read().splitlines()
    for name in PROFILE_NAMES.values():
        matches = [line for line in lines if line.startswith(name + " (")]
        if len(matches) != 1 or not matches[0].endswith(" (enforce)"):
            return False
    return True


def main(package_dir, run=default_run, euid=None, loaded=loaded_enforce):
    """`run`, `euid` and `loaded` exist for tests only; production calls main(package_dir)."""
    if (os.geteuid() if euid is None else euid) != 0:
        raise Stop("not_root")
    if os.path.islink(package_dir) or not os.path.isdir(package_dir):
        raise Stop("package_directory_invalid")
    st = os.lstat(package_dir)
    if st.st_uid != 0 or stat.S_IMODE(st.st_mode) & 0o022:
        raise Stop("package_directory_owner_or_mode_invalid")
    package = {}
    for target, name in SOURCE_NAMES.items():
        package[target] = read_regular(os.path.join(package_dir, name), None)
        if sha(package[target]) != NEW[target]:
            raise Stop("package_file_hash_mismatch:" + name)
    try:
        package.update(generated_profiles(package[CONTRACT]))
    except Exception:
        raise Stop("package_contract_unusable")
    for path in (PROFILE_P, PROFILE_R):
        if sha(package[path]) != NEW[path]:
            raise Stop("generated_profile_hash_mismatch:" + os.path.basename(path))
    for path in ORDER:
        if os.path.lexists(temp_name(path)):
            raise Stop("leftover_temporary_file")
    if sha(read_regular(HELPER, MODES[HELPER])) != HELPER_SHA:
        raise Stop("installed_helper_not_the_pinned_hotfix")
    current = {path: read_regular(path, MODES[path]) for path in ORDER}
    state = {path: sha(data) for path, data in current.items()}
    already = all(state[p] == NEW[p] for p in ORDER)
    if not already and any(state[p] != OLD[p] for p in ORDER):
        raise Stop("installed_files_unrecognized")
    for unit in UNITS:
        done = run(["/usr/bin/systemctl", "is-active", unit])
        if done.returncode != 3 or done.stdout.strip() not in ("inactive", b"inactive"):
            raise Stop("g1_unit_not_inactive")
    try:
        if not loaded():
            raise Stop("profile_not_loaded_enforce")
    except OSError:
        raise Stop("apparmor_status_unavailable")
    for path in (PROFILE_P, PROFILE_R):
        done = run([PARSER, "-Q", "-T"], package[path])
        if done.returncode != 0:
            raise Stop("new_profile_does_not_compile:" + os.path.basename(path))

    def reload_profiles():
        for path in (PROFILE_P, PROFILE_R):
            done = run([PARSER, "-r", path])
            if done.returncode != 0:
                raise Stop("profile_reload_failed:" + os.path.basename(path))

    def verify():
        done = run(["/usr/bin/python3", "-I", "-B", "-c", STATIC_VERIFY_SNIPPET])
        out = done.stdout.decode("ascii", "replace") if isinstance(done.stdout, bytes) else done.stdout
        if done.returncode != 0 or "STATIC_INSTALL_VERIFY=PASS" not in out or "BASE_CONFIG_CHECK=PASS" not in out:
            found = re.search(r"G1_MYSQL=STOP;CODE=([a-z0-9_]{1,80})", out)
            raise Stop("verify_static_install_failed" + (":" + found.group(1) if found else ""))
        try:
            if not loaded():
                raise Stop("profile_not_loaded_enforce_after_reload")
        except OSError:
            raise Stop("apparmor_status_unavailable")

    if already:
        # Idempotent heal: a previous run may have been interrupted between the file swap and the reload.
        reload_profiles()
        verify()
        return "G1_GO52C_PROFILE_UPGRADE=PASS;NOTE=already_upgraded"
    try:
        for path in ORDER:
            replace_atomic(path, package[path], MODES[path])
        for path in ORDER:
            if sha(read_regular(path, MODES[path])) != NEW[path]:
                raise Stop("post_write_hash_mismatch")
        reload_profiles()
        verify()
    except BaseException as exc:
        restored = True
        for path in reversed(ORDER):
            try:
                if sha(read_regular(path, MODES[path])) != OLD[path]:
                    replace_atomic(path, current[path], MODES[path])
                if sha(read_regular(path, MODES[path])) != OLD[path]:
                    restored = False
            except BaseException:
                restored = False
        try:
            for path in (PROFILE_P, PROFILE_R):
                if run([PARSER, "-r", path]).returncode != 0:
                    restored = False
        except BaseException:
            restored = False
        code = exc.code if isinstance(exc, Stop) else "internal_error:" + exc.__class__.__name__
        raise Stop(code, rolled_back="yes" if restored else "NO")
    return "G1_GO52C_PROFILE_UPGRADE=PASS"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("G1_GO52C_PROFILE_UPGRADE=STOP;CODE=usage")
        raise SystemExit(2)
    try:
        print(main(sys.argv[1]))
        code = 0
    except Stop as exc:
        extra = f";ROLLED_BACK={exc.rolled_back}" if exc.rolled_back else ""
        print(f"G1_GO52C_PROFILE_UPGRADE=STOP;CODE={exc.code}{extra}")
        code = 3
    except BaseException as exc:
        print(f"G1_GO52C_PROFILE_UPGRADE=STOP;CODE=internal_error:{exc.__class__.__name__}")
        code = 4
    raise SystemExit(code)

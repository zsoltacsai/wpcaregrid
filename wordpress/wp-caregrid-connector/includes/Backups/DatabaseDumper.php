<?php

namespace WPCareGrid\Connector\Backups;

use WPCareGrid\Connector\Core\Lock;

/**
 * Exports this site's tables (those with the WordPress table prefix) to a
 * gzip-compressed SQL file, locally. Database credentials are only used
 * here, to open a second connection from wp-config.php; they never leave
 * the site and are not written anywhere.
 *
 * - One consistent snapshot (InnoDB), on its own connection, so the site
 *   and the connector keep working meanwhile.
 * - Rows are read in batches; memory does not grow with the table size.
 * - Output uses a strict, simple form that SqlImporter validates on
 *   restore: one statement per line; INSERT values are only NULL or quoted
 *   strings.
 * - Not exported: transients (regenerated by WordPress) and the connector's
 *   own state (its credential and job records).
 */
final class DatabaseDumper
{
    private const BATCH = 500;

    private const STATEMENT_BYTES = 1048576;

    /** Database jobs need MySQL or MariaDB through wpdb/mysqli. */
    public static function supported(): bool
    {
        global $wpdb;

        return $wpdb instanceof \wpdb && get_class($wpdb) === 'wpdb' && $wpdb->dbh instanceof \mysqli;
    }

    /** Approximate size of this site's tables, for the disk-space check. */
    public static function estimate(): int
    {
        global $wpdb;

        return (int) $wpdb->get_var($wpdb->prepare(
            'SELECT SUM(data_length) FROM information_schema.TABLES WHERE table_schema = %s AND table_name LIKE %s',
            DB_NAME,
            $wpdb->esc_like($wpdb->base_prefix).'%'
        ));
    }

    /** @return array{path: string, size: int, sha256: string, compression: string, engine: string, server_version: string, charset: string, table_prefix: string, tables: int, rows: int, excluded: array} */
    public function dump(string $uuid): array
    {
        global $wpdb;

        if (! self::supported()) {
            throw new BackupFailure('DATABASE_NOT_SUPPORTED', 'Database backups need MySQL or MariaDB.');
        }

        $db = new \wpdb(DB_USER, DB_PASSWORD, DB_NAME, DB_HOST);
        $db->suppress_errors(true);
        $db->show_errors(false);

        if (! $db->dbh instanceof \mysqli || ! $db->get_var('SELECT 1')) {
            throw new BackupFailure('DATABASE_DUMP_FAILED', 'The database could not be opened for the backup.');
        }

        $server = (string) $db->db_server_info();
        $prefix = $wpdb->base_prefix;
        $sink = new Sink(TempDir::file($uuid, Sink::gzip_available() ? 'database.sql.gz' : 'database.sql'), true);
        $rows_total = 0;

        try {
            $db->query('SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ');
            $db->query('START TRANSACTION WITH CONSISTENT SNAPSHOT');

            $tables = array_values(array_filter(
                (array) $db->get_col("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'"),
                fn ($table) => is_string($table) && str_starts_with($table, $prefix) && preg_match('/^[A-Za-z0-9_$]+$/', $table)
            ));

            $sink->write("-- WP CareGrid database backup\n");
            $sink->write('SET NAMES '.preg_replace('/[^a-z0-9_]/', '', (string) $db->charset).";\n");
            $sink->write("SET FOREIGN_KEY_CHECKS = 0;\n");
            $sink->write("SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n");

            foreach ($tables as $table) {
                $rows_total += $this->table($db, $sink, $table, $prefix);
            }

            $sink->write("SET FOREIGN_KEY_CHECKS = 1;\n");
            $db->query('COMMIT');
        } catch (\Throwable $e) {
            try {
                $sink->close();
            } catch (\Throwable) {
            }
            throw $e instanceof BackupFailure ? $e : new BackupFailure('DATABASE_DUMP_FAILED', 'The database export failed.');
        } finally {
            $db->close();
        }

        return $sink->close() + [
            'engine' => stripos($server, 'mariadb') !== false ? 'mariadb' : 'mysql',
            'server_version' => substr(preg_replace('/[^0-9A-Za-z.+~_-]/', '', $server) ?: 'unknown', 0, 64),
            'charset' => preg_replace('/[^a-z0-9_]/', '', (string) $db->charset) ?: 'utf8mb4',
            'table_prefix' => $prefix,
            'tables' => count($tables),
            'rows' => $rows_total,
            'excluded' => ['transients', 'connector_state'],
        ];
    }

    private function table(\wpdb $db, Sink $sink, string $table, string $prefix): int
    {
        $create = $db->get_row("SHOW CREATE TABLE `{$table}`", ARRAY_N);
        if (! is_array($create) || ! isset($create[1])) {
            throw new BackupFailure('DATABASE_DUMP_FAILED', 'A table definition could not be read.');
        }

        $sink->write("DROP TABLE IF EXISTS `{$table}`;\n");
        $sink->write(str_replace(["\r\n", "\n", "\r"], ' ', $create[1]).";\n");

        $where = $this->exclusions($db, $table, $prefix);
        $order = $this->primary_key_order($db, $table);
        $rows = 0;

        for ($offset = 0; ; $offset += self::BATCH) {
            $batch = $db->get_results("SELECT * FROM `{$table}`{$where}{$order} LIMIT ".self::BATCH.' OFFSET '.$offset, ARRAY_N);
            if ($db->last_error !== '') {
                throw new BackupFailure('DATABASE_DUMP_FAILED', 'A table could not be read.');
            }
            if (! $batch) {
                break;
            }

            $values = [];
            $bytes = 0;
            foreach ($batch as $row) {
                $tuple = '('.implode(',', array_map(fn ($value) => $value === null ? 'NULL' : "'".$db->remove_placeholder_escape($db->_real_escape((string) $value))."'", $row)).')';
                $values[] = $tuple;
                $bytes += strlen($tuple);

                if ($bytes >= self::STATEMENT_BYTES) {
                    $sink->write("INSERT INTO `{$table}` VALUES ".implode(',', $values).";\n");
                    $values = [];
                    $bytes = 0;
                }
            }
            if ($values) {
                $sink->write("INSERT INTO `{$table}` VALUES ".implode(',', $values).";\n");
            }

            $rows += count($batch);
            $db->flush();
            Lock::refresh();

            if (count($batch) < self::BATCH) {
                break;
            }
        }

        return $rows;
    }

    /** Transients and the connector's own options are left out. */
    private function exclusions(\wpdb $db, string $table, string $prefix): string
    {
        $quoted = preg_quote($prefix, '/');

        if (preg_match('/^'.$quoted.'(\d+_)?options$/', $table)) {
            return $db->prepare(
                ' WHERE option_name NOT LIKE %s AND option_name NOT LIKE %s AND option_name NOT LIKE %s',
                $db->esc_like('_transient_').'%',
                $db->esc_like('_site_transient_').'%',
                $db->esc_like('wp_caregrid_').'%'
            );
        }

        if ($table === $prefix.'sitemeta') {
            return $db->prepare(' WHERE meta_key NOT LIKE %s', $db->esc_like('_site_transient_').'%');
        }

        return '';
    }

    private function primary_key_order(\wpdb $db, string $table): string
    {
        $keys = (array) $db->get_results("SHOW KEYS FROM `{$table}` WHERE Key_name = 'PRIMARY'", ARRAY_A);
        usort($keys, fn ($a, $b) => (int) $a['Seq_in_index'] <=> (int) $b['Seq_in_index']);
        $columns = array_filter(array_map(fn ($key) => preg_match('/^[A-Za-z0-9_$]+$/', (string) $key['Column_name']) ? '`'.$key['Column_name'].'`' : null, $keys));

        return $columns ? ' ORDER BY '.implode(', ', $columns) : '';
    }
}
